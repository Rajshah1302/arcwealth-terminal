// Exports human-readable ABIs (functions, events, errors) for the frontend into src/shared/abis.ts.
import { formatAbi } from 'abitype'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { ROOT, loadArtifact } from '../server/chain'

const map: Record<string, string> = {
  vaultAbi: 'SIFStrategyVault', investorVaultAbi: 'InvestorVault', routerAbi: 'DemoSwapRouter', demoTokenAbi: 'DemoERC20',
  lendingAbi: 'DemoLendingPool', strategyManagerAbi: 'StrategyManager', riskManagerAbi: 'RiskManager', oracleAbi: 'DemoPriceOracle',
  issuerAbi: 'DemoBondIssuer', coveredCallAbi: 'CoveredCallModule', bondModuleAbi: 'BondInvestmentModule', tacticalAbi: 'TacticalSleeveModule',
  timelockAbi: 'ArcWealthTimelock',
}
let out = '// GENERATED by scripts/export-abis.ts. Do not edit.\nimport { parseAbi } from \'viem\'\n\n'
for (const [k, n] of Object.entries(map)) {
  const abi = loadArtifact(n).abi.filter((i) => i.type === 'function' || i.type === 'event' || i.type === 'error')
  out += `export const ${k} = parseAbi(${JSON.stringify(formatAbi(abi), null, 1)})\n\n`
}
writeFileSync(resolve(ROOT, 'src/shared/abis.ts'), out)
console.log('abis written')
